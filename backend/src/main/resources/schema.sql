-- V1 schema for the staffing MVP. H2 2.x, run on every start; IF NOT EXISTS keeps a
-- file database restartable, and data.sql MERGEs so a restart never duplicates a seed.
-- Vocabularies live here as CHECK constraints so the database refuses a band or a state
-- the specs never defined; every rule with a condition stays in domain/.

CREATE TABLE IF NOT EXISTS role (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(40) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_role_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(60) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20) NOT NULL,
    display_name  VARCHAR(120) NOT NULL,
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (role IN ('LEAD', 'COORDINATOR'))
);

-- One role domain per skill: role_domain_id is NOT NULL, so a skill is never under two roles.
CREATE TABLE IF NOT EXISTS skill (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(60) NOT NULL,
    role_domain_id BIGINT NOT NULL,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_skill_name UNIQUE (name),
    CONSTRAINT fk_skill_domain FOREIGN KEY (role_domain_id) REFERENCES role (id)
);

-- One role per person: a single NOT NULL reference. There is no person_role table, so no
-- code path can add a second role.
CREATE TABLE IF NOT EXISTS person (
    employee_no VARCHAR(20) NOT NULL PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    email       VARCHAR(160),
    role_id     BIGINT NOT NULL,
    job_level   VARCHAR(20) NOT NULL,
    travel      VARCHAR(20) NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_person_role FOREIGN KEY (role_id) REFERENCES role (id),
    CONSTRAINT ck_person_job_level CHECK (job_level IN ('Junior', 'Senior', 'Lead', 'Principal')),
    CONSTRAINT ck_person_travel CHECK (travel IN ('none', 'limited', 'full'))
);

-- At most one band per person and skill; an import overwrites it and never deletes it.
CREATE TABLE IF NOT EXISTS person_skill (
    employee_no VARCHAR(20) NOT NULL,
    skill_id    BIGINT NOT NULL,
    band        VARCHAR(20) NOT NULL,
    CONSTRAINT pk_person_skill PRIMARY KEY (employee_no, skill_id),
    CONSTRAINT fk_person_skill_person FOREIGN KEY (employee_no) REFERENCES person (employee_no),
    CONSTRAINT fk_person_skill_skill FOREIGN KEY (skill_id) REFERENCES skill (id),
    CONSTRAINT ck_person_skill_band
        CHECK (band IN ('Novice', 'Advanced beginner', 'Practitioner', 'Proficient', 'Expert'))
);

-- A project carries its own range: the spec stores name, lead, start date and end date, and
-- refuses an end date before the start. status OPEN -> CLOSED is terminal.
CREATE TABLE IF NOT EXISTS project (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    lead_user_id BIGINT NOT NULL,
    start_date   DATE NOT NULL,
    end_date     DATE NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    CONSTRAINT fk_project_lead FOREIGN KEY (lead_user_id) REFERENCES app_user (id),
    CONSTRAINT ck_project_dates CHECK (start_date <= end_date),
    CONSTRAINT ck_project_status CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE TABLE IF NOT EXISTS post (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT NOT NULL,
    title           VARCHAR(120),
    role_id         BIGINT NOT NULL,
    min_job_level   VARCHAR(20) NOT NULL,
    headcount       INT NOT NULL,
    start_date      DATE NOT NULL,
    end_date        DATE NOT NULL,
    travel_required VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'open',
    CONSTRAINT fk_post_project FOREIGN KEY (project_id) REFERENCES project (id),
    CONSTRAINT fk_post_role FOREIGN KEY (role_id) REFERENCES role (id),
    CONSTRAINT ck_post_headcount CHECK (headcount >= 1),
    CONSTRAINT ck_post_dates CHECK (start_date <= end_date),
    CONSTRAINT ck_post_min_job_level
        CHECK (min_job_level IN ('Junior', 'Senior', 'Lead', 'Principal')),
    CONSTRAINT ck_post_travel CHECK (travel_required IN ('none', 'limited', 'full')),
    CONSTRAINT ck_post_status
        CHECK (status IN ('open', 'partially filled', 'filled', 'cancelled'))
);

-- A required row carries its minimum band, a bonus row its target band; never both, never none.
CREATE TABLE IF NOT EXISTS post_skill (
    post_id     BIGINT NOT NULL,
    skill_id    BIGINT NOT NULL,
    kind        VARCHAR(10) NOT NULL,
    min_band    VARCHAR(20),
    target_band VARCHAR(20),
    CONSTRAINT pk_post_skill PRIMARY KEY (post_id, skill_id),
    CONSTRAINT fk_post_skill_post FOREIGN KEY (post_id) REFERENCES post (id),
    CONSTRAINT fk_post_skill_skill FOREIGN KEY (skill_id) REFERENCES skill (id),
    CONSTRAINT ck_post_skill_kind CHECK (kind IN ('REQUIRED', 'BONUS')),
    CONSTRAINT ck_post_skill_bands CHECK (
        (kind = 'REQUIRED' AND min_band IS NOT NULL AND target_band IS NULL)
        OR (kind = 'BONUS' AND target_band IS NOT NULL AND min_band IS NULL))
);

-- A release deletes the assignment with its allocation (spec: releasing reopens the slot),
-- so a row here is always an active assignment and carries no state column.
CREATE TABLE IF NOT EXISTS assignment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT NOT NULL,
    person_no  VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_assignment_post_person UNIQUE (post_id, person_no),
    CONSTRAINT fk_assignment_post FOREIGN KEY (post_id) REFERENCES post (id),
    CONSTRAINT fk_assignment_person FOREIGN KEY (person_no) REFERENCES person (employee_no)
);

CREATE TABLE IF NOT EXISTS allocation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_no     VARCHAR(20) NOT NULL,
    project_id    BIGINT NOT NULL,
    start_date    DATE NOT NULL,
    end_date      DATE NOT NULL,
    source        VARCHAR(20) NOT NULL,
    assignment_id BIGINT,
    CONSTRAINT fk_allocation_person FOREIGN KEY (person_no) REFERENCES person (employee_no),
    CONSTRAINT fk_allocation_project FOREIGN KEY (project_id) REFERENCES project (id),
    CONSTRAINT fk_allocation_assignment FOREIGN KEY (assignment_id) REFERENCES assignment (id),
    CONSTRAINT ck_allocation_dates CHECK (start_date <= end_date),
    CONSTRAINT ck_allocation_source CHECK (
        (source = 'MANUAL' AND assignment_id IS NULL)
        OR (source = 'CONFIRMATION' AND assignment_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS recommendation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT NOT NULL,
    person_no     VARCHAR(20) NOT NULL,
    state         VARCHAR(20) NOT NULL DEFAULT 'proposed',
    void_reason   VARCHAR(20),
    note          VARCHAR(500),
    snapshot_json CLOB NOT NULL,
    proposed_by   BIGINT NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_recommendation_post FOREIGN KEY (post_id) REFERENCES post (id),
    CONSTRAINT fk_recommendation_person FOREIGN KEY (person_no) REFERENCES person (employee_no),
    CONSTRAINT fk_recommendation_user FOREIGN KEY (proposed_by) REFERENCES app_user (id),
    CONSTRAINT ck_recommendation_state
        CHECK (state IN ('proposed', 'confirmed', 'rejected', 'withdrawn', 'voided')),
    CONSTRAINT ck_recommendation_void CHECK (
        (state = 'voided' AND void_reason IN ('person taken', 'post changed', 'post cancelled'))
        OR (state <> 'voided' AND void_reason IS NULL))
);

CREATE TABLE IF NOT EXISTS notice (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordinator_id BIGINT NOT NULL,
    person_no      VARCHAR(20) NOT NULL,
    post_id        BIGINT NOT NULL,
    reason         VARCHAR(20) NOT NULL,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dismissed_at   TIMESTAMP,
    CONSTRAINT fk_notice_user FOREIGN KEY (coordinator_id) REFERENCES app_user (id),
    CONSTRAINT fk_notice_person FOREIGN KEY (person_no) REFERENCES person (employee_no),
    CONSTRAINT fk_notice_post FOREIGN KEY (post_id) REFERENCES post (id),
    CONSTRAINT ck_notice_reason
        CHECK (reason IN ('person taken', 'post changed', 'post cancelled'))
);

-- No row at all when the workbook is unreadable; a REJECTED batch keeps its full error list.
CREATE TABLE IF NOT EXISTS import_batch (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename    VARCHAR(255) NOT NULL,
    status      VARCHAR(20) NOT NULL,
    uploaded_by BIGINT NOT NULL,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    person_rows INT NOT NULL DEFAULT 0,
    skill_rows  INT NOT NULL DEFAULT 0,
    error_count INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_import_batch_uploader FOREIGN KEY (uploaded_by) REFERENCES app_user (id),
    CONSTRAINT ck_import_batch_status CHECK (status IN ('APPLIED', 'REJECTED')),
    CONSTRAINT ck_import_batch_rows CHECK (person_rows >= 0 AND skill_rows >= 0),
    CONSTRAINT ck_import_batch_error_count CHECK (error_count >= 0)
);

CREATE TABLE IF NOT EXISTS import_error (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    sheet    VARCHAR(20) NOT NULL,
    row_no   INT NOT NULL,
    key_value VARCHAR(80),
    message  VARCHAR(500) NOT NULL,
    CONSTRAINT fk_import_error_batch FOREIGN KEY (batch_id) REFERENCES import_batch (id),
    CONSTRAINT ck_import_error_row_no CHECK (row_no >= 1)
);
